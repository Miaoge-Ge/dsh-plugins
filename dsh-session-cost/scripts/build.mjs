import {readFile,writeFile} from 'node:fs/promises';
const root = new URL('../',import.meta.url);
const read = p => readFile(new URL(p,root),'utf8');
const core = (await read('src/accounting.mjs')).replace(/^export /gm,'');
const balance = (await read('src/balance.mjs')).replace(/^export /gm,'');
const loader = (await read('src/loader.mjs')).replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');
const css = await read('src/style.css');
const client = (await read('src/client.js')).replace('/*__CORE__*/',()=>core+'\n'+loader+'\n'+balance).replace('/*__CSS__*/',()=>`const CSS = ${JSON.stringify(css)};`);
await writeFile(new URL('client.js',root),'// Generated by npm run build. Edit src/.\n'+client);
console.log('Built usage billing dashboard.');
