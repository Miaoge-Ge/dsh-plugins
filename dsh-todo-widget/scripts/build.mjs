import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');

const model = (await read('src/model.mjs')).replace(/^export /gm, '');
const css = await read('src/style.css');
const zh = JSON.parse(await read('locale/zh.json'));
const en = JSON.parse(await read('locale/en.json'));

const dictionaries = `const DICTIONARIES = ${JSON.stringify({ zh: zh.ui, en: en.ui }, null, 2)};`;

const client = (await read('src/client.js'))
  .replace('/*__MODEL__*/', () => model.trimEnd())
  .replace('/*__LOCALES__*/', () => dictionaries)
  .replace('/*__CSS__*/', () => `const CSS = ${JSON.stringify(css)};`);

if (client.includes('/*__MODEL__*/') || client.includes('/*__LOCALES__*/') || client.includes('/*__CSS__*/')) {
  throw new Error('A build placeholder was not replaced.');
}

await writeFile(new URL('client.js', root), `// Generated by npm run build. Edit src/.\n${client}`);
console.log('Built the daily to-do widget.');
