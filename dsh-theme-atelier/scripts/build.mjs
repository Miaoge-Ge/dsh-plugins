import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { validateTheme, contrast } from '../src/tokens.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFile(resolve(root, path), 'utf8');
const files = (await readdir(resolve(root, 'themes'))).filter(name => name.endsWith('.json')).sort();
const themes = await Promise.all(files.map(async file => validateTheme(JSON.parse(await read(`themes/${file}`)))));
if (new Set(themes.map(t => t.id)).size !== themes.length) throw new Error('Duplicate theme id');
for (const theme of themes) for (const mode of ['light', 'dark']) {
  const p = theme[mode];
  for (const surface of ['bg', 'sidebar', 'surface', 'raised', 'soft', 'code']) for (const label of ['text', 'muted', 'accent']) {
    if (contrast(p[label], p[surface]) < 4.5) throw new Error(`${theme.id}/${mode}: ${label} on ${surface} needs 4.5:1 contrast`);
  }
  if (contrast(p.accent, p.onAccent) < 4.5) throw new Error(`${theme.id}/${mode}: accent button needs 4.5:1 contrast`);
}
const locales = Object.fromEntries(await Promise.all(['zh', 'en'].map(async lang => [lang, JSON.parse(await read(`locale/${lang}.json`))])));
const core = (await read('src/tokens.mjs')).replace(/^export /gm, '');
const css = await read('src/style.css');
let client = await read('src/client.js');
client = client.replace('/*__CATALOG__*/', () => `const themes = ${JSON.stringify(themes)};`)
  .replace('/*__CORE__*/', () => core)
  .replace('/*__LOCALES__*/', () => `const dictionaries = ${JSON.stringify(locales)};`)
  .replace('/*__STYLES__*/', () => `const styles = ${JSON.stringify(css)};`);
await writeFile(resolve(root, 'client.js'), '// Generated by npm run build. Edit src/ and themes/.\n' + client);
await writeFile(resolve(root, 'catalog.js'), `// Generated theme data.\nexport const themes = ${JSON.stringify(themes, null, 2)};\n`);
console.log(`Built ${themes.length} design families / ${themes.length * 2} palettes; all text and accent pairs pass 4.5:1.`);
